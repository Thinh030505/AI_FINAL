/**
 * Retrieves a vocabulary item by its integer class ID.
 * Returns undefined if classId is out of bounds [0..79].
 */
export function getVocabularyByClassId(classId: number): CocoVocabularyItem | undefined {
  if (typeof classId !== 'number' || Number.isNaN(classId)) {
    return undefined;
  }
  return COCO_DICTIONARY_BY_ID[classId];
}

/**
 * Retrieves a vocabulary item by its label string (case-insensitive, trimmed).
 * Returns undefined if label does not match any COCO class.
 */
export function getVocabularyByLabel(label: string): CocoVocabularyItem | undefined {
  if (!label || typeof label !== 'string') {
    return undefined;
  }
  const normalized = label.toLowerCase().trim();
  return COCO_DICTIONARY_BY_LABEL[normalized];
}

/**
 * Universal lookup helper accepting either numeric classId or string label.
 */
export function getVocabulary(query: number | string): CocoVocabularyItem | undefined {
  if (typeof query === 'number') {
    return getVocabularyByClassId(query);
  }
  return getVocabularyByLabel(query);
}
